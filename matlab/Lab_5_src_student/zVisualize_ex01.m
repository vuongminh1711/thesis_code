function zVisualize_ex01(prmLTE, txSig, rxSig)
% Constellation Scopes & Spectral Analyzers
persistent hScope1 hSpecAnalyzer
% Constellation Diagrams
if isempty(hScope1)
hScope1 = comm.ConstellationDiagram('ShowReferenceConstellation', false,...
    'YLimits', [-3,3], 'XLimits', [-3,3], 'Position', ...
    figposition([5 60 17 30]), 'Name', 'After Channel Model');
% Spectrum Scope
    % D. Tan 2024-09-13 
    hSpecAnalyzer = spectrumAnalyzer(SampleRate=prmLTE.chanSRate, ...
        SpectrumType='power-density', SpectrumUnits='dBw',...
        RBWSource='property',   RBW=15e3, ...
        FrequencySpan='span-and-center-frequency', ...
        Span=0.5*prmLTE.chanSRate, CenterFrequency=0, ...
        Method='welch', Window='rectangular', ...
        YLimits=[-80 -55], YLabel='PSD', ...
        Title='Transmitted & Received Signal Spectrum', ...
        ChannelNames={'Transmitted', 'Received'}, ShowLegend=false); %'PowerUnits', 'dBW'
end
% Update Spectrum scope
step(hSpecAnalyzer, [txSig, rxSig]);
% Update Constellation Scope
step(hScope1, rxSig);
end